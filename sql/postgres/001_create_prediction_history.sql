CREATE TABLE IF NOT EXISTS ml_prediction_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,
    machine_id VARCHAR(50) NOT NULL,
    temperature DOUBLE PRECISION NOT NULL,
    pressure DOUBLE PRECISION NOT NULL,
    vibration DOUBLE PRECISION NOT NULL,
    run_hours DOUBLE PRECISION NOT NULL,
    alarm_count INTEGER NOT NULL,
    maintenance_days INTEGER NOT NULL,
    fault_probability NUMERIC(9,8) NOT NULL CHECK (fault_probability >= 0 AND fault_probability <= 1),
    prediction BOOLEAN NOT NULL,
    risk_level VARCHAR(10) NOT NULL CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH')),
    threshold NUMERIC(5,4) NOT NULL,
    model_version VARCHAR(50) NOT NULL,
    actual_fault BOOLEAN NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actual_fault_updated_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_ml_prediction_history_machine_created
    ON ml_prediction_history(machine_id, created_at DESC);

CREATE INDEX IF NOT EXISTS ix_ml_prediction_history_model_created
    ON ml_prediction_history(model_version, created_at DESC);
